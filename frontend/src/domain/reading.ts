export function readingLesson(mode: ReadingMode, round: number): ReadingCard[] {
  const cards = material[mode]
  return Array.from({ length: 6 }, (_, index) => ({
    words: cards[(round * 6 + index) % cards.length].split(' ').map(word => word.split('-')),
  }))
}
